"""gen_durations.py - Write Data/AuraDurations.lua: the full duration of every
aura the alert pearls watch (#21 Buff alerts, #22 Paladin tank reminders), from
the client's own tables: SpellMisc (DifficultyID 0) -> DurationIndex ->
SpellDuration.Duration (milliseconds). It gives the approximate timer ("~12")
when only Blizzard's proc overlay says a buff is there; a plain aura read always
gives the exact one. -1 (until cancelled) and a missing row are written as 0:
no timer.

Reads the local wago.tools exports (References/Forever/db, fetched once per
build with References/Tools/Wago/wago.py get SpellMisc SpellDuration). Never
fetches anything itself.

Usage (from the repo root):
    python Tools/gen_durations.py                 # the newest saved build
    python Tools/gen_durations.py 1.60.1.70532
"""
import csv
import glob
import os
import re
import sys

HERE = os.path.dirname(__file__)
DB = os.path.join(HERE, "..", "..", "References", "Forever", "db")
OUT = os.path.join(HERE, "..", "Data", "AuraDurations.lua")

# Every aura ID an alert pearl watches, by pearl and entry (the pearls' own lists).
IDS = {
    "buffs: Clearcasting": [12536, 16246, 16870, 457342, 467735],
    "buffs: Innervate": [29166, 456195],
    "buffs: Power Infusion": [10060],
    "buffs: Blessing of Protection": [1022, 5599, 10278, 442948],
    "buffs: Blessing of Sacrifice": [6940, 20729],
    "buffs: Blessing of Freedom": [1044],
    "paladintank: Righteous Fury": [25780, 407627],
    "paladintank: Salvation": [1038, 25895],
}


def build_of(path):
    return re.search(r"-(\d+\.\d+\.\d+\.\d+)\.csv$", path).group(1)


def newest_build():
    files = glob.glob(os.path.join(DB, "forever-spellmisc-*.csv"))
    if not files:
        sys.exit("no SpellMisc export in %s: python References/Tools/Wago/wago.py get SpellMisc SpellDuration" % DB)
    return build_of(max(files, key=lambda p: tuple(int(x) for x in build_of(p).split("."))))


def rows(table, build):
    path = os.path.join(DB, "forever-%s-%s.csv" % (table, build))
    if not os.path.exists(path):
        sys.exit("missing %s: python References/Tools/Wago/wago.py get %s --build %s" % (path, table, build))
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else newest_build()
    duration = {int(r["ID"]): int(r["Duration"] or 0) for r in rows("spellduration", build)}
    names = {int(r["ID"]): r["Name_lang"] for r in rows("spellname", build)}
    wanted = {i for ids in IDS.values() for i in ids}
    index = {}
    for r in rows("spellmisc", build):
        sid = int(r["SpellID"] or 0)
        if sid in wanted and int(r["DifficultyID"] or 0) == 0:
            index[sid] = int(r["DurationIndex"] or 0)
    lines = [
        "-- Data/AuraDurations.lua: GENERATED by Tools/gen_durations.py from the client's",
        "-- SpellMisc and SpellDuration tables (build %s, wago.tools). Do not edit:" % build,
        "-- re-run the script after a new build. The full duration, in seconds, of each",
        "-- aura the alert pearls watch: the approximate timer when only Blizzard's proc",
        "-- overlay says a buff is there. 0: until cancelled, or not in the tables.",
        "",
        "GlassPearls = GlassPearls or {}",
        "GlassPearls.AuraDurations = {",
        "    build = \"%s\"," % build,
    ]
    for label, ids in IDS.items():
        for sid in ids:
            ms = duration.get(index.get(sid, -1), 0)
            seconds = ms // 1000 if ms > 0 else 0
            lines.append("    [%d] = %d,   -- %s (%s)" % (sid, seconds, names.get(sid, "?"), label))
    lines.append("}")
    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("%d durations from build %s -> %s" % (len(wanted), build, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
