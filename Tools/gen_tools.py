"""gen_tools.py - Write Core/ToolItems.lua: every item the client marks as a
tool (ItemSparse.TotemCategoryID > 0: shaman totems, mining picks, skinning
knives, blacksmith hammers, spanners, enchanting rods, ...). The bags-full
helper never offers one to destroy.

Reads the local wago.tools exports (References/Forever/db, fetched once per
build with References/Tools/Wago/wago.py). Never fetches anything itself.

Usage (from the repo root):
    python Tools/gen_tools.py                 # the newest saved build
    python Tools/gen_tools.py 1.60.1.70532
"""
import csv
import glob
import os
import re
import sys

DB = os.path.join(os.path.dirname(__file__), "..", "..", "References", "Forever", "db")
OUT = os.path.join(os.path.dirname(__file__), "..", "Core", "ToolItems.lua")


def newest(table):
    files = glob.glob(os.path.join(DB, "forever-%s-*.csv" % table))
    if not files:
        sys.exit("no %s export in %s: python References/Tools/Wago/wago.py get %s" % (table, DB, table))

    def build(path):
        return tuple(int(x) for x in re.search(r"-(\d+\.\d+\.\d+\.\d+)\.csv$", path).group(1).split("."))
    return max(files, key=build)


def main():
    if len(sys.argv) > 1:
        build = sys.argv[1]
        items = os.path.join(DB, "forever-itemsparse-%s.csv" % build)
        cats = os.path.join(DB, "forever-totemcategory-%s.csv" % build)
    else:
        items, cats = newest("itemsparse"), newest("totemcategory")
        build = re.search(r"-(\d+\.\d+\.\d+\.\d+)\.csv$", items).group(1)
    with open(cats, newline="", encoding="utf-8") as f:
        names = {int(r["ID"]): r["Name_lang"] for r in csv.DictReader(f)}
    tools = []
    with open(items, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            cat = int(r["TotemCategoryID"] or 0)
            if cat > 0:
                tools.append((int(r["ID"]), cat, r["Display_lang"]))
    tools.sort()
    lines = [
        "-- Core/ToolItems.lua: GENERATED by Tools/gen_tools.py from the client's",
        "-- ItemSparse and TotemCategory tables (build %s, wago.tools). Do not edit:" % build,
        "-- re-run the script after a new build. Every item the client marks as a tool",
        "-- (TotemCategoryID > 0). The bags-full helper never offers one to destroy.",
        "",
        "GlassPearls = GlassPearls or {}",
        "GlassPearls.ToolItems = {",
        "    build = \"%s\"," % build,
    ]
    for item, cat, name in tools:
        lines.append("    [%d] = true,   -- %s (%s)" % (item, name.replace("\n", " "), names.get(cat, cat)))
    lines.append("}")
    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("%d tools from build %s -> %s" % (len(tools), build, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
